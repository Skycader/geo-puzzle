// Builds levels/dmzZone.js — Korean Demilitarized Zone as a countries-level
// Overview "Зоны" overlay (same projection as scripts/build_countries_level.js).
//
// Source: OSM relation 6794199 via polygons.openstreetmap.fr →
//   scripts/data/korean-dmz-osm.json, then mapshaper-simplified into
//   scripts/data/korean-dmz-simplified.geojson.
//
// Regenerate geometry:
//   curl.exe -sL -A "geo-puzzle-dev/1.0" -o scripts/data/korean-dmz-osm.json ^
//     "https://polygons.openstreetmap.fr/get_geojson.py?id=6794199&params=0"
//   npx mapshaper -i scripts/data/korean-dmz-osm.json -simplify 8% keep-shapes ^
//     -o format=geojson scripts/data/korean-dmz-simplified.geojson
//   node scripts/build_dmz_zone.js
const fs = require('fs');
const path = require('path');

const SRC = path.join(__dirname, 'data', 'korean-dmz-simplified.geojson');
const OUT = path.join(__dirname, '..', 'levels', 'dmzZone.js');

const SCALE = 3.2;
const project = (lon, lat) => [(lon + 180) * SCALE, (90 - lat) * SCALE];
const KM_PER_UNIT = 111.32 / SCALE;

function ringToPath(ring) {
  const pts = ring.map(([lon, lat]) => project(lon, lat));
  return 'M ' + pts.map(([x, y]) => `${x.toFixed(2)},${y.toFixed(2)}`).join(' L ') + ' Z';
}

function ringAreaCentroid(ring) {
  const pts = ring.map(([lon, lat]) => project(lon, lat));
  let a = 0,
    cx = 0,
    cy = 0;
  for (let i = 0; i < pts.length; i++) {
    const [x1, y1] = pts[i];
    const [x2, y2] = pts[(i + 1) % pts.length];
    const cross = x1 * y2 - x2 * y1;
    a += cross;
    cx += (x1 + x2) * cross;
    cy += (y1 + y2) * cross;
  }
  a *= 0.5;
  if (Math.abs(a) < 1e-12) {
    let sx = 0,
      sy = 0;
    for (const [x, y] of pts) {
      sx += x;
      sy += y;
    }
    return { x: sx / pts.length, y: sy / pts.length, area: 0 };
  }
  return { x: cx / (6 * a), y: cy / (6 * a), area: Math.abs(a) };
}

function ringBbox(ring, bbox) {
  for (const [lon, lat] of ring) {
    const [x, y] = project(lon, lat);
    bbox[0] = Math.min(bbox[0], x);
    bbox[1] = Math.min(bbox[1], y);
    bbox[2] = Math.max(bbox[2], x);
    bbox[3] = Math.max(bbox[3], y);
  }
}

const geo = JSON.parse(fs.readFileSync(SRC, 'utf8'));
const feat = geo.features ? geo.features[0] : geo;
if (!feat?.geometry) throw new Error('No geometry in ' + SRC);

const polys =
  feat.geometry.type === 'Polygon'
    ? [feat.geometry.coordinates]
    : feat.geometry.type === 'MultiPolygon'
      ? feat.geometry.coordinates
      : null;
if (!polys?.length) throw new Error('Expected Polygon/MultiPolygon in ' + SRC);

const bbox = [Infinity, Infinity, -Infinity, -Infinity];
const pathParts = [];
let nativeArea = 0;
let best = null;
for (const poly of polys) {
  const outer = poly[0];
  const stats = ringAreaCentroid(outer);
  nativeArea += stats.area;
  if (!best || stats.area > best.area) best = stats;
  ringBbox(outer, bbox);
  pathParts.push(ringToPath(outer));
  for (let h = 1; h < poly.length; h++) pathParts.push(ringToPath(poly[h]));
}

const zone = {
  id: 'dmz',
  name: 'Demilitarized Zone (DMZ)',
  ru: 'Демилитаризованная зона (DMZ)',
  overlay: true,
  cx: +best.x.toFixed(1),
  cy: +best.y.toFixed(1),
  bbox: bbox.map((n) => +n.toFixed(1)),
  area: Math.round(nativeArea * KM_PER_UNIT * KM_PER_UNIT),
  d: pathParts.join(' '),
  labelPoints: [[+best.x.toFixed(1), +best.y.toFixed(1)]],
};

let out = `// Auto-generated by scripts/build_dmz_zone.js — Korean DMZ as a\n`;
out += `// countries-level zone overlay (Overview → Зоны). Same equirectangular\n`;
out += `// projection as scripts/build_countries_level.js.\n`;
out += `// Regenerate: node scripts/build_dmz_zone.js\n`;
out += `export default ${JSON.stringify(zone, null, 2)};\n`;

fs.writeFileSync(OUT, out, 'utf8');
console.error('wrote', OUT, zone.area + ' km²', polys.length, 'part(s)', 'path', zone.d.length, 'chars');
