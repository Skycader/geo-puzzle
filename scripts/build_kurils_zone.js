// Extracts the Kuril Islands rings from Russia's Natural Earth admin-0
// multipolygon and writes levels/kurilsZone.js — a countries-level ZONE
// (overview "Зоны" tab), same projection as scripts/build_countries_level.js.
//
// Kept as an overlay (`overlay: true`): the islands stay part of Russia's
// country piece for games; the zone is a translucent highlight on top.
// Same lon/lat box as applyRussiaFarEastLabels in build_countries_level.js.
//
// Regenerate: node scripts/build_kurils_zone.js
const fs = require('fs');
const path = require('path');

const LAND_SRC = path.join(__dirname, 'data', 'world-countries-simplified.geojson');
const OUT = path.join(__dirname, '..', 'levels', 'kurilsZone.js');

const SCALE = 3.2;
const project = (lon, lat) => [(lon + 180) * SCALE, (90 - lat) * SCALE];
const KM_PER_UNIT = 111.32 / SCALE;
const isKuril = (lon, lat) => lon >= 145.5 && lon <= 157 && lat >= 43 && lat <= 51;

const POLE_LAT_EPSILON = 0.01;
const isAtPole = (lat) => Math.abs(lat) > 90 - POLE_LAT_EPSILON;

function unwrapRingLons(ring) {
  const first = ring[0];
  const last = ring[ring.length - 1];
  const pts = first[0] === last[0] && first[1] === last[1] ? ring.slice(0, -1) : ring;
  const out = [pts[0]];
  let offset = 0;
  for (let i = 1; i < pts.length; i++) {
    const d = pts[i][0] - pts[i - 1][0];
    const poleTouch = isAtPole(pts[i][1]) || isAtPole(pts[i - 1][1]);
    if (!poleTouch) {
      if (d > 180) offset -= 360;
      else if (d < -180) offset += 360;
    }
    out.push([pts[i][0] + offset, pts[i][1]]);
  }
  return out;
}

function ringToPath(ring) {
  const pts = unwrapRingLons(ring).map(([lon, lat]) => project(lon, lat));
  return 'M ' + pts.map(([x, y]) => `${x.toFixed(2)},${y.toFixed(2)}`).join(' L ') + ' Z';
}

function ringAreaCentroid(ring) {
  const pts = unwrapRingLons(ring).map(([lon, lat]) => project(lon, lat));
  let a = 0,
    cx = 0,
    cy = 0;
  for (let i = 0; i < pts.length; i++) {
    const [x1, y1] = pts[i];
    const [x2, y2] = pts[(i + 1) % pts.length];
    const cross = x1 * y2 - x2 * y1;
    a += cross;
    cx += (x1 + x2) * cross;
    cy += (y1 + y2) * cross;
  }
  a *= 0.5;
  return { x: cx / (6 * a), y: cy / (6 * a), area: Math.abs(a) };
}

function ringBbox(ring, bbox) {
  for (const [lon, lat] of unwrapRingLons(ring)) {
    const [x, y] = project(lon, lat);
    bbox[0] = Math.min(bbox[0], x);
    bbox[1] = Math.min(bbox[1], y);
    bbox[2] = Math.max(bbox[2], x);
    bbox[3] = Math.max(bbox[3], y);
  }
}

const geo = JSON.parse(fs.readFileSync(LAND_SRC, 'utf8'));
const rus = geo.features.find((f) => f.properties.NAME === 'Russia');
if (!rus) throw new Error('Russia feature missing from world-countries-simplified.geojson');

const polys = [];
for (const poly of rus.geometry.coordinates) {
  const ring = poly[0];
  let slon = 0,
    slat = 0;
  for (const p of ring) {
    slon += p[0];
    slat += p[1];
  }
  if (isKuril(slon / ring.length, slat / ring.length)) polys.push(poly);
}
if (!polys.length) throw new Error('No Kuril rings found in Russia multipolygon');

const bbox = [Infinity, Infinity, -Infinity, -Infinity];
const pathParts = [];
let nativeArea = 0;
let best = null;
for (const poly of polys) {
  const stats = ringAreaCentroid(poly[0]);
  nativeArea += stats.area;
  if (!best || stats.area > best.area) best = stats;
  ringBbox(poly[0], bbox);
  pathParts.push(ringToPath(poly[0]));
}

const zone = {
  id: 'kurils',
  name: 'Kuril Islands',
  // Display name requested as «Курильский полуостров» (the feature is the
  // island arc; listed under Overview → Зоны).
  ru: 'Курильский полуостров',
  overlay: true,
  cx: +best.x.toFixed(1),
  cy: +best.y.toFixed(1),
  bbox: bbox.map((n) => +n.toFixed(1)),
  area: Math.round(nativeArea * KM_PER_UNIT * KM_PER_UNIT),
  d: pathParts.join(' '),
  labelPoints: [[+best.x.toFixed(1), +best.y.toFixed(1)]],
};

let out = `// Auto-generated by scripts/build_kurils_zone.js — Kuril Islands as a\n`;
out += `// countries-level zone overlay (Overview → Зоны). Same equirectangular\n`;
out += `// projection as scripts/build_countries_level.js.\n`;
out += `// Regenerate: node scripts/build_kurils_zone.js\n`;
out += `export default ${JSON.stringify(zone, null, 2)};\n`;

fs.writeFileSync(OUT, out, 'utf8');
console.error('wrote', OUT, zone.area + ' km²', polys.length, 'islands');
