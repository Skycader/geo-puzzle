// Builds the world-map cities and places:
//   levels/worldCities.js — capitals + the biggest cities (scripts/data/world-cities-source.json,
//                            produced from Natural Earth by scripts/extract_world_cities.js)
//   levels/worldPlaces.js — hand-picked interesting places (PLACES below)
// Both are attached to the "world" and "countries" levels in levels/index.js; they share
// the equirectangular projection of scripts/build_world_seas.js / build_countries_level.js.
// Unlike the USA cities there is no real land-area data, so a city carries `pop`
// (Natural Earth's POP_MAX, approximate) instead of `radiusKm`; js/overviewBoard.js draws
// such cities as constant-size dots and lists population instead of area.
// Regenerate: node scripts/build_world_cities.js
const fs = require('fs');
const path = require('path');
const { pathToFileURL } = require('url');

const SCALE = 3.2; // must match build_world_seas.js (1152 / 360)
const project = (lat, lon) => [+((lon + 180) * SCALE).toFixed(1), +((90 - lat) * SCALE).toFixed(1)];

// [id, name, ru, lat, lon]
const PLACES = [
  // Settlement on the Russia–North Korea border (Tumen River), the southernmost
  // settlement of the Russian Far East; coordinates from Wikipedia's own record.
  ['khasan', 'Khasan', 'Хасан', 42.42833, 130.64556],
  // Joint Security Area in the Korean DMZ, where the two Koreas hold talks; Wikipedia's coordinates.
  ['panmunjom', 'Panmunjom', 'Пханмунджом', 37.956, 126.677],
  // Unification observatory at the confluence of the Han and Imjin rivers, looking over the DMZ at
  // North Korea; coordinates from the Korean Wikipedia article (the only language that has one).
  ['odusan', 'Odusan Unification Observatory', 'Обзорная вышка Одусан', 37.773139, 126.67725],
];

// Natural Earth gives these countries an ISO code of -99 / a code that doesn't match
// levels/countries.js's ids, so their Russian name is supplied by hand.
const RU_COUNTRY_FALLBACK = { France: 'Франция', Israel: 'Израиль', Norway: 'Норвегия', Somaliland: 'Сомалиленд', Kosovo: 'Косово' };

const slug = (s) =>
  s.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_|_$/g, '');
const q = (s) => s.replace(/\\/g, '\\\\').replace(/'/g, "\\'");

(async () => {
  const cities = JSON.parse(fs.readFileSync(path.join(__dirname, 'data', 'world-cities-source.json'), 'utf8'));
  const { default: countries } = await import(pathToFileURL(path.join(__dirname, '..', 'levels', 'countries.js')));
  const ruByA3 = new Map(countries.pieces.map((p) => [p.id.toUpperCase(), p.ru]));

  const seen = new Set();
  const rows = cities.map((c) => {
    let id = slug(c.name);
    if (seen.has(id)) id += '_' + c.a3.toLowerCase();
    seen.add(id);
    const [cx, cy] = project(c.lat, c.lon);
    return { id, name: c.name, ru: c.ru, state: ruByA3.get(c.a3) || RU_COUNTRY_FALLBACK[c.country] || c.country, stateEn: c.country, capital: c.capital, cx, cy, pop: c.pop };
  });
  const noRu = [...new Set(cities.filter((c) => !ruByA3.has(c.a3) && !RU_COUNTRY_FALLBACK[c.country]).map((c) => c.country))];
  console.error('cities', rows.length, '| countries without a Russian name in countries.js (English shown):', noRu.join(', ') || '-');

  let out = '// Auto-generated by scripts/build_world_cities.js — capitals and the biggest cities of the world\n';
  out += '// (Natural Earth populated places, public domain), projected like levels/world.js. `pop` is\n';
  out += "// Natural Earth's POP_MAX (approximate); `state` is the country name (ru), `stateEn` (en).\n";
  out += '// Regenerate: node scripts/build_world_cities.js\nexport default [\n';
  for (const r of rows) {
    out += `  { id: '${r.id}', name: '${q(r.name)}', ru: '${q(r.ru)}', state: '${q(r.state)}', stateEn: '${q(r.stateEn)}', capital: ${r.capital}, cx: ${r.cx}, cy: ${r.cy}, pop: ${r.pop} },\n`;
  }
  out += '];\n';
  fs.writeFileSync(path.join(__dirname, '..', 'levels', 'worldCities.js'), out, 'utf8');

  let pl = '// Auto-generated by scripts/build_world_cities.js — hand-picked places for the world map.\n';
  pl += '// Regenerate: node scripts/build_world_cities.js\nexport default [\n';
  for (const [id, name, ru, lat, lon] of PLACES) {
    const [cx, cy] = project(lat, lon);
    pl += `  { id: '${id}', name: '${q(name)}', ru: '${q(ru)}', cx: ${cx}, cy: ${cy}, radiusKm: 2 },\n`;
  }
  pl += '];\n';
  fs.writeFileSync(path.join(__dirname, '..', 'levels', 'worldPlaces.js'), pl, 'utf8');
  console.error('wrote levels/worldCities.js, levels/worldPlaces.js');
})();
